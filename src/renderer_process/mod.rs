//! Renderer Process - 渲染器进程
//!
//! 每个标签页对应一个独立的渲染器进程（此处为线程实现）。
//! 通过 Mojo IPC 接收浏览器进程的导航 / 输入事件，
//! 将渲染结果以 PNG 帧的形式发回浏览器进程。
//!
//! # 架构
//!
//! ```text
//! ┌──────────────────────────────────────────────────────────┐
//! │                    Renderer Process                      │
//! │                                                          │
//! │  ┌──────────────────────────────────────────────────┐    │
//! │  │              Mojo IPC (3 channels)               │    │
//! │  │  ┌──────────┐  ┌───────────┐  ┌──────────────┐  │    │
//! │  │  │ Navigate │  │ Input     │  │ RenderResult  │  │    │
//! │  │  │ (Browser │  │ (Browser  │  │ (Renderer  →  │  │    │
//! │  │  │  → Rdr)  │  │  → Rdr)   │  │  → Browser)   │  │    │
//! │  │  └────┬─────┘  └─────┬─────┘  └──────┬───────┘  │    │
//! │  └───────┼──────────────┼────────────────┼──────────┘    │
//! │          ▼              ▼                │               │
//! │  ┌────────────────────────────────────┐  │               │
//! │  │       Renderer Instance            │  │               │
//! │  │  (kuchiki DOM, tiny-skia paint,    │◄─┘               │
//! │  │   cosmic-text rendering)           │                  │
//! │  └────────────────────────────────────┘                  │
//! └──────────────────────────────────────────────────────────┘
//! ```

